@file:OptIn(ExperimentalAssociatedObjects::class)

package dev.whyoleg.sweetspi

import kotlin.concurrent.Volatile
import kotlin.jvm.*
import kotlin.reflect.*

/**
 * with https://youtrack.jetbrains.com/issue/KT-75442/Add-compiler-plugin-extension-point-for-modifying-whole-world-IR-on-klib-backends
 * we can also optimize on link phase and remove EagerInit calls at all, just inline initializers code - like R8 does
 * so there could be following rewrites:
 * ```
 * // before
 * ServiceLoader.load<SimpleService>()
 * // after 1 phase
 * SimpleService.`$Registry`.load() // returns Sequence<T> (or similar call)
 * // after 2 phase
 * sequence {
 *   emit(SimpleServiceProvider1.value) // or even simpler
 *   emit(SimpleServiceProvider2.value)
 *   emit(SimpleServiceProvider3.value)
 *   emit(SimpleServiceProvider4.value)
 * }
 * ```
 * TBD: R8 could also start to optimize kotlin.ServiceLoader
 */

public actual object ServiceLoader {
    public actual inline fun <reified T : Any> load(): Sequence<T> = load(T::class)
    public actual inline fun <reified T : Any> loadProviders(): Sequence<Provider<T>> = loadProviders(T::class)

    @JvmStatic
    public actual fun <T : Any> load(cls: KClass<T>): Sequence<T> = getRegistry(cls).load()

    @JvmStatic
    public actual fun <T : Any> loadProviders(cls: KClass<T>): Sequence<Provider<T>> = getRegistry(cls).loadProviders()

    @Suppress("UNCHECKED_CAST")
    private fun <T : Any> getRegistry(cls: KClass<T>): Registry<T> {
        return cls.findAssociatedObject<ServiceRegistryHolder>() as? Registry<T> ?: error(
            "Service registry not found for class ${cls.qualifiedName}"
        )
    }

    public actual interface Provider<T : Any> : Lazy<T> {
        public actual val type: KClass<out T>
    }

    @PublishedApi // impl generated by compiler
    internal abstract class Registry<T : Any> {
        @Volatile
        private var initialized = false
        private val initializers = mutableListOf<() -> Provider<T>>()

        // this is `public` API
        fun register(provider: () -> Provider<T>) {
            require(!initialized) { "Service registry is already initialized" }
            initializers.add(provider)
        }

        internal fun load(): Sequence<T> {
            initialized = true
            return initializers.asSequence().map { it().value }.constrainOnce()
        }

        internal fun loadProviders(): Sequence<Provider<T>> {
            initialized = true
            return initializers.asSequence().map { it() }.constrainOnce()
        }
    }
}

@AssociatedObjectKey
@Retention(AnnotationRetention.BINARY)
internal annotation class ServiceRegistryHolder(val registry: KClass<out ServiceLoader.Registry<*>>)
