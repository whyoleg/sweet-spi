package dev.whyoleg.sweetspi

import kotlin.concurrent.*
import kotlin.reflect.*

public actual open class ServiceLoader private constructor() {
    public actual companion object Default : ServiceLoader()

    public actual inline fun <reified T : Any> load(): Sequence<ServiceProvider<T>> = load(T::class)
    public actual fun <T : Any> load(type: KClass<T>): Sequence<ServiceProvider<T>> = ServiceProviderRegistryHolder.getRegistry(type).load()
}

/**
 * with https://youtrack.jetbrains.com/issue/KT-75442/Add-compiler-plugin-extension-point-for-modifying-whole-world-IR-on-klib-backends
 * we can also optimize on link phase and remove EagerInit calls at all, just inline initializers code - like R8 does
 * so there could be following rewrites:
 * ```
 * // before
 * ServiceLoader.load<SimpleService>()
 * // after 1 phase
 * `SimpleService$ServiceProviderRegistry`.load() // returns Sequence<T> (or similar call)
 * // after 2 phase
 * sequence {
 *   emit(SimpleServiceProvider1.value) // or even simpler
 *   emit(SimpleServiceProvider2.value)
 *   emit(SimpleServiceProvider3.value)
 *   emit(SimpleServiceProvider4.value)
 * }
 * ```
 * TBD: R8 could also start to optimize kotlin.ServiceLoader
 */

@PublishedApi // impl generated by compiler
internal abstract class ServiceProviderRegistry<T : Any> {
    @Volatile
    private var initialized = false
    private val initializers = mutableListOf<() -> ServiceProvider<T>>()

    // this is `public` API used by compiler plugin
    fun register(initializer: () -> ServiceProvider<T>) {
        require(!initialized) { "Service registry is already initialized" }
        initializers.add(initializer)
    }

    internal fun load(): Sequence<ServiceProvider<T>> {
        initialized = true
        return initializers.asSequence().map { it() }.constrainOnce()
    }
}

@OptIn(ExperimentalAssociatedObjects::class)
@AssociatedObjectKey
@Retention(AnnotationRetention.BINARY)
internal annotation class ServiceProviderRegistryHolder(val registry: KClass<out ServiceProviderRegistry<*>>) {
    companion object {
        fun <T : Any> getRegistry(cls: KClass<T>): ServiceProviderRegistry<T> {
            @Suppress("UNCHECKED_CAST")
            return cls.findAssociatedObject<ServiceProviderRegistryHolder>() as? ServiceProviderRegistry<T> ?: error(
                "Service registry not found for class ${cls.simpleName}"
            )
        }
    }
}
